export function cariUniversitas(query: string, limit = 8): UniversitasItem[] {
  const q = query.trim().toLowerCase();
  if (!q) {
    return UNIVERSITAS_INDONESIA.slice(0, limit);
  }

  const exactOrPrefix: UniversitasItem[] = [];
  const partial: UniversitasItem[] = [];

  for (const item of UNIVERSITAS_INDONESIA) {
    const namaLower = item.nama.toLowerCase();
    const singkatanMatch = item.singkatan?.some((s) => s.toLowerCase() === q || s.toLowerCase().startsWith(q));
    if (singkatanMatch || namaLower.startsWith(q)) {
      exactOrPrefix.push(item);
    } else if (
      namaLower.includes(q) ||
      item.singkatan?.some((s) => s.toLowerCase().includes(q)) ||
      item.kota?.toLowerCase().includes(q)
    ) {
      partial.push(item);
    }
  }

  return [...exactOrPrefix, ...partial].slice(0, limit);
}
